import { REQUEST_TIMEOUT_MS } from '../../api/http';
import type { ApiError } from '../../api/http';
import type { TicketRequest } from '../../types/ticket';

/** Объясняет механику, почему заявка не создана и что делать дальше. */
export function describeTicketError(error: ApiError, request: TicketRequest): string {
  switch (error.kind) {
    case 'not_configured':
      return 'Адрес системы ТОиР не задан в настройках приложения. Заявка не отправлена. Обратитесь к администратору.';
    case 'network':
      return 'Система ТОиР недоступна. Заявка не отправлена. Проверьте связь и подтвердите заявку ещё раз.';
    case 'timeout':
      // Запрос мог дойти: повторная отправка вслепую создала бы вторую заявку.
      return (
        `Система ТОиР не ответила за ${REQUEST_TIMEOUT_MS / 1000} секунд. Неизвестно, создана ли заявка: ` +
        'проверьте это в ТОиР, прежде чем отправлять её снова.'
      );
    case 'not_found':
      return (
        `Система ТОиР не знает машину ${request.vehicle_id} или её проверку ${request.session_id}. ` +
        'Заявка не создана. Возможно, список машин в приложении устарел.'
      );
    case 'validation':
      return 'Система ТОиР отклонила заявку: её состав не соответствует правилам ТОиР. Заявка не создана. Проверьте поля и отправьте ещё раз.';
    case 'http':
      return `Система ТОиР ответила ошибкой (код ${error.httpStatus ?? 'неизвестен'}). Номер заявки не получен. Подтвердите её ещё раз позже.`;
    case 'invalid_response':
      return (
        'Система ТОиР прислала ответ, который приложение не смогло разобрать. Номер заявки неизвестен: ' +
        'проверьте в ТОиР, создана ли она, прежде чем отправлять её снова.'
      );
    case 'unknown':
      return 'Не удалось отправить заявку. Подтвердите её ещё раз.';
  }
}
